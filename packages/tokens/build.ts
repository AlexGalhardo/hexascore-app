// Emits tokens.css (CSS variables + Tailwind v4 @theme mapping) and tokens.ts from tokens.json.
// Run: bun run --cwd packages/tokens build
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { type Mode, oklchToHex } from "./color";
import tokens from "./tokens.json";

const dir = import.meta.dirname;
const names = Object.keys(tokens.color) as (keyof typeof tokens.color)[];

export function renderCss(): string {
	const vars = (mode: Mode): string =>
		names.map((n) => `\t--hs-${n}: oklch(${tokens.color[n][mode]});`).join("\n");
	const theme = names.map((n) => `\t--color-${n}: var(--hs-${n});`).join("\n");
	const radius = Object.entries(tokens.radius)
		.map(([k, v]) => `\t--radius-${k}: ${v}px;`)
		.join("\n");
	return `/* Generated by packages/tokens/build.ts from tokens.json. Do not edit. */
:root {
${vars("light")}
}

.dark {
${vars("dark")}
}

@theme inline {
${theme}
${radius}
}
`;
}

export function renderTs(): string {
	const modes = (["light", "dark"] as const).map((mode) => {
		const entries = names.map((n) => {
			const oklch = tokens.color[n][mode];
			return `\t\t${JSON.stringify(n)}: { oklch: "oklch(${oklch})", hex: "${oklchToHex(oklch)}" },`;
		});
		return `\t${mode}: {\n${entries.join("\n")}\n\t},`;
	});
	return `// Generated by packages/tokens/build.ts from tokens.json. Do not edit.
export const colors = {
${modes.join("\n")}
} as const;

export const spacing = ${JSON.stringify(tokens.spacing)} as const;
export const fontSize = ${JSON.stringify(tokens.fontSize)} as const;
export const radius = ${JSON.stringify(tokens.radius)} as const;
export const touchTarget = ${tokens.touchTarget};
`;
}

if (import.meta.main) {
	writeFileSync(join(dir, "tokens.css"), renderCss());
	writeFileSync(join(dir, "tokens.ts"), renderTs());
}
